function mudarTexto() {
    document.querySelector("h1").innerText = "Texto alterado!";
}

function mudarCor() {
    document.querySelector("h1").style.color = "blue";
}
function mudarFonte() {
    document.querySelector("h1").style.fontFamily = "Arial, sans-serif";
}   

function mudarTamanho() {
    document.querySelector("h1").style.fontSize = "40px";
}   

function mudarFundo() {
    document.querySelector("body").style.backgroundColor = "lightgray";
}   